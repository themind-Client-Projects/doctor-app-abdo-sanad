/**
 * Give one account per STAFF role a password, and write the logins to a file.
 *
 * `seed.ts` already creates an account for every role, but only
 * `admin@warid.app` ever had a password: onboarding deliberately leaves the
 * hash blank "for an administrator to set afterwards", and until the users
 * screen was wired there was nowhere to do it. So eight of the nine roles
 * could not sign in at all.
 *
 * PATIENT is excluded on purpose and is not a gap: `src/lib/auth.ts` makes
 * email+password the STAFF door, and the phone-OTP provider refuses any role
 * other than PATIENT. A patient signs in by phone (or Google), never by
 * password — the file this writes lists their phone numbers instead.
 *
 * Existing accounts are reused rather than duplicated. Passwords are random
 * per run and written ONLY to SEED_LOGINS.local.md, which is gitignored —
 * this repo is pushed to a client organisation.
 *
 *   npm run seed-logins
 */
import path from "node:path";
import { randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import { config as loadEnv } from "dotenv";

loadEnv({ path: path.join(process.cwd(), ".env.local") });
loadEnv({ path: path.join(process.cwd(), ".env") });

/** The account to use for each staff role, preferring the seeded @warid.app one. */
const PREFERRED: Record<string, string> = {
  SUPER_ADMIN: "admin@warid.app",
  OPERATIONS: "ops@warid.app",
  DOCTOR: "dr.ali@warid.app",
  LAB: "lab@warid.app",
  PHARMACY: "pharmacy@warid.app",
  NURSE: "nurse1@warid.app",
  DRIVER: "driver1@warid.app",
  RADIOLOGY: "radiology@warid.app",
};

/** Readable enough to type during testing, random enough not to be guessable. */
function makePassword(role: string): string {
  return `Warid.${role.charAt(0)}${role.slice(1).toLowerCase()}.${randomBytes(4).toString("hex")}`;
}

async function main() {
  const { prisma } = await import("../src/lib/prisma");
  const bcrypt = (await import("bcryptjs")).default;

  const rows: { role: string; email: string; password: string; name: string; partner: string }[] = [];

  for (const [role, email] of Object.entries(PREFERRED)) {
    let user = await prisma.user.findUnique({
      where: { email },
      select: { id: true, name: true, role: true, partner: { select: { name: true } } },
    });

    // Fall back to any account already holding the role, rather than inventing
    // a second one beside it.
    if (!user) {
      user = await prisma.user.findFirst({
        where: { role: role as never, deletedAt: null },
        select: { id: true, name: true, role: true, partner: { select: { name: true } } },
      });
    }
    if (!user) {
      console.warn(`  no account for ${role} — skipped`);
      continue;
    }

    const password = makePassword(role);
    await prisma.user.update({
      where: { id: user.id },
      data: {
        passwordHash: await bcrypt.hash(password, 10),
        // A deactivated account cannot sign in; these are meant to be usable.
        isActive: true,
      },
    });

    rows.push({
      role,
      email,
      password,
      name: user.name ?? "—",
      partner: user.partner?.name ?? "—",
    });
    console.log(`  ${role.padEnd(12)} ${email}`);
  }

  const patients = await prisma.user.findMany({
    where: { role: "PATIENT", deletedAt: null, phone: { not: null } },
    select: { name: true, phone: true },
    take: 4,
  });

  const file = [
    "# Warid — seeded test logins",
    "",
    "> Generated by `npm run seed-logins`. **Gitignored on purpose** — this repo is",
    "> pushed to a client organisation. Re-run the script to rotate them.",
    "",
    "## Staff — sign in at `/login` with email + password",
    "",
    "| Role | Email | Password | Name | Partner |",
    "| --- | --- | --- | --- | --- |",
    ...rows.map((r) => `| ${r.role} | \`${r.email}\` | \`${r.password}\` | ${r.name} | ${r.partner} |`),
    "",
    "Where each lands after signing in: SUPER_ADMIN → `/admin`, OPERATIONS →",
    "`/operations`, every provider role → `/dashboard`. A super admin may also open",
    "`/operations` and `/dashboard`.",
    "",
    "## Patients — no password by design",
    "",
    "`src/lib/auth.ts` makes email+password the staff door, and the phone-OTP",
    "provider refuses any role but PATIENT. Patients sign in at `/signin` by phone",
    "(OTP over WhatsApp) or with Google — never a password.",
    "",
    "| Name | Phone |",
    "| --- | --- |",
    ...patients.map((p) => `| ${p.name ?? "—"} | \`${p.phone}\` |`),
    "",
  ].join("\n");

  writeFileSync(path.join(process.cwd(), "SEED_LOGINS.local.md"), file, "utf8");
  console.log(`\n${rows.length} staff logins written to SEED_LOGINS.local.md (gitignored).`);

  await prisma.$disconnect();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
